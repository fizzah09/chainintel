"""Report export endpoint: POST /api/v1/reports/export

Accepts a report payload and returns a PDF, CSV, or JSON file.  Stateless — the caller
(frontend) provides the content; nothing is persisted here.
"""

import csv
import io
import json
from datetime import datetime
from typing import Annotated, Literal

from fastapi import APIRouter, Depends
from fastapi.responses import Response, StreamingResponse
from pydantic import BaseModel

from app.core.security import require_principal

router = APIRouter(prefix="/api/v1", tags=["Reports"], dependencies=[Depends(require_principal)])


class ReportSection(BaseModel):
    heading: str
    content: str


class ReportMeta(BaseModel):
    org: str = "Chain Intel"
    date: str = ""
    generated_by: str = ""
    report_id: str = ""
    subject: str = ""


class ExportRequest(BaseModel):
    title: str
    sections: list[ReportSection]
    meta: ReportMeta = ReportMeta()
    fmt: Literal["pdf", "csv", "json"] = "pdf"


@router.post("/reports/export")
def export_report(body: ExportRequest) -> Response:
    if body.fmt == "json":
        return _as_json(body)
    if body.fmt == "csv":
        return _as_csv(body)
    return _as_pdf(body)


# ---- JSON --------------------------------------------------------------------------------------

def _as_json(body: ExportRequest) -> Response:
    payload = {
        "title": body.title,
        "meta": body.meta.model_dump(),
        "sections": [{"heading": s.heading, "content": s.content} for s in body.sections],
        "exported_at": datetime.utcnow().isoformat() + "Z",
    }
    return Response(
        content=json.dumps(payload, indent=2),
        media_type="application/json",
        headers={"Content-Disposition": f'attachment; filename="{_safe(body.title)}.json"'},
    )


# ---- CSV ---------------------------------------------------------------------------------------

def _as_csv(body: ExportRequest) -> Response:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["Report", body.title])
    w.writerow(["Subject", body.meta.subject])
    w.writerow(["Generated by", body.meta.generated_by])
    w.writerow(["Date", body.meta.date])
    w.writerow([])
    w.writerow(["Section", "Content"])
    for s in body.sections:
        w.writerow([s.heading, s.content])
    return Response(
        content=buf.getvalue(),
        media_type="text/csv",
        headers={"Content-Disposition": f'attachment; filename="{_safe(body.title)}.csv"'},
    )


# ---- PDF ---------------------------------------------------------------------------------------

def _as_pdf(body: ExportRequest) -> Response:
    try:
        from fpdf import FPDF

        pdf = FPDF()
        pdf.set_auto_page_break(auto=True, margin=15)
        pdf.add_page()
        pdf.set_margins(20, 20, 20)

        # Header
        pdf.set_font("Helvetica", "B", 16)
        pdf.set_text_color(15, 20, 30)
        pdf.multi_cell(0, 9, body.title, align="L")
        pdf.ln(2)

        pdf.set_font("Helvetica", "", 9)
        pdf.set_text_color(100, 110, 120)
        meta_line = "  |  ".join(filter(None, [
            body.meta.org,
            f"Subject: {body.meta.subject}" if body.meta.subject else "",
            f"By: {body.meta.generated_by}" if body.meta.generated_by else "",
            body.meta.date,
            body.meta.report_id,
        ]))
        pdf.multi_cell(0, 5, meta_line, align="L")
        pdf.ln(1)

        # Divider
        pdf.set_draw_color(220, 225, 230)
        pdf.line(20, pdf.get_y(), 190, pdf.get_y())
        pdf.ln(5)

        # Sections
        for i, s in enumerate(body.sections, 1):
            pdf.set_font("Helvetica", "B", 11)
            pdf.set_text_color(30, 40, 60)
            pdf.multi_cell(0, 7, f"{i}. {s.heading}", align="L")
            pdf.ln(1)

            pdf.set_font("Helvetica", "", 10)
            pdf.set_text_color(50, 60, 70)
            pdf.multi_cell(0, 6, s.content, align="L")
            pdf.ln(5)

        raw = pdf.output()
        return Response(
            content=bytes(raw),
            media_type="application/pdf",
            headers={"Content-Disposition": f'attachment; filename="{_safe(body.title)}.pdf"'},
        )
    except ImportError:
        # fpdf2 not installed: fall back to plain-text
        lines = [body.title, "=" * len(body.title), ""]
        for s in body.sections:
            lines += [s.heading, "-" * len(s.heading), s.content, ""]
        return Response(
            content="\n".join(lines),
            media_type="text/plain",
            headers={"Content-Disposition": f'attachment; filename="{_safe(body.title)}.txt"'},
        )


def _safe(name: str) -> str:
    return "".join(c if c.isalnum() or c in " -_" else "_" for c in name)[:60].strip()
